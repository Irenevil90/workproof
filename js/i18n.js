let currentLang = localStorage.getItem('wp_lang') || 'en';

function t(key) { return T[currentLang]?.[key] || key; }

function toggleLanguage() {
  currentLang = currentLang === 'en' ? 'es' : 'en';
  localStorage.setItem('wp_lang', currentLang);
  applyTranslations();
  updateLangToggle();
}

function applyTranslations() {
  // 1. Static data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    var val = t(key);
    if (el.tagName === 'INPUT') el.placeholder = val;
    else el.textContent = val;
  });

  // 2. Translate ALL text nodes in labels/buttons/divs by content lookup
  var selectors = 'button, .btn, .nav-item, .field-label, .lb-subtitle, .lb-title, .stat-label, .sc-title, .sc-timer-label, label, .topbar-title, .opt-desc, .opt-title';
  document.querySelectorAll(selectors).forEach(function(el) {
    // Only translate leaf nodes (no child elements besides spans)
    var children = el.children;
    if (children.length === 0 || (children.length === 1 && children[0].tagName === 'SPAN' && children[0].classList.contains('nav-icon'))) {
      var span = children.length === 1 ? children[0] : null;
      var txt = span ? el.textContent.replace(span.textContent, '').trim() : el.textContent.trim();
      if (txt && txt.length > 1) {
        var tr = t(txt);
        if (tr !== txt) {
          if (span) {
            // nav item: keep icon span, translate text
            el.innerHTML = span.outerHTML + tr;
          } else {
            el.textContent = tr;
          }
        }
      }
    }
  });

  // 3. Translate field labels (uppercase mono labels)
  document.querySelectorAll('.field-label, [class*="label"]').forEach(function(el) {
    if (el.children.length === 0) {
      var txt = el.textContent.trim();
      var tr = t(txt);
      if (tr !== txt) el.textContent = tr;
    }
  });

  // 4. Translate placeholder attributes
  document.querySelectorAll('[placeholder]').forEach(function(el) {
    var ph = el.getAttribute('placeholder');
    var tr = t(ph);
    if (tr !== ph) el.placeholder = tr;
  });

  document.documentElement.lang = currentLang;
}

function updateLangToggle() {
  var btn = document.getElementById('lang-toggle');
  if (!btn) return;
  btn.textContent = currentLang === 'en' ? '🇪🇸 ES' : '🇬🇧 EN';
  btn.title = currentLang === 'en' ? 'Cambiar a Español' : 'Switch to English';
}

// Hook into screen navigation to re-apply translations
var _i18nInterval = null;
function scheduleTranslation() {
  clearTimeout(_i18nInterval);
  _i18nInterval = setTimeout(applyTranslations, 80);
}

// Observer for DOM changes (catches dynamically built content)
var _observer = null;
document.addEventListener('DOMContentLoaded', function() {
  applyTranslations();
  updateLangToggle();

  // Watch for major DOM changes (leaderboard builds, vote cards, etc.)
  if (window.MutationObserver) {
    _observer = new MutationObserver(function(mutations) {
      var hasRelevant = mutations.some(function(m) {
        return m.addedNodes.length > 0;
      });
      if (hasRelevant && currentLang === 'es') scheduleTranslation();
    });
    _observer.observe(document.body, { childList: true, subtree: true });
  }
});
