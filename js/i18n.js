let currentLang = localStorage.getItem('wp_lang') || 'en';

function t(key) {
  return T[currentLang]?.[key] || key;
}

function toggleLanguage() {
  currentLang = currentLang === 'en' ? 'es' : 'en';
  localStorage.setItem('wp_lang', currentLang);
  applyTranslations();
  updateLangToggle();
}

function applyTranslations() {
  // Static elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    var val = t(key);
    if (el.tagName === 'INPUT') el.placeholder = val;
    else el.textContent = val;
  });

  // Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  // Translate button text by content (for dynamically built buttons)
  var btns = ['Yes, good day','Not really','Skip','Continue →','← Back','← Exit',
              'Join challenge →','Open dashboard →','Save profile','Connect Calendar',
              'Connect GitHub','Leave challenge','Back to home','Details'];
  document.querySelectorAll('button, .btn').forEach(function(el) {
    var txt = el.textContent.trim();
    if (btns.indexOf(txt) !== -1) el.textContent = t(txt);
  });

  // Translate nav items
  document.querySelectorAll('.nav-item').forEach(function(el) {
    var span = el.querySelector('span:last-child');
    if (span && !span.classList.contains('nav-icon') && !span.classList.contains('nav-badge')) {
      var key = span.textContent.trim();
      var tr = t(key);
      if (tr !== key) span.textContent = tr;
    }
  });

  // Translate specific text nodes in sidebar
  ['sc-title','lb-subtitle'].forEach(function(cls) {
    document.querySelectorAll('.'+cls).forEach(function(el) {
      var key = el.textContent.trim();
      var tr = t(key);
      if (tr !== key) el.textContent = tr;
    });
  });

  // Update direction/font for ES
  document.documentElement.lang = currentLang;
}

function updateLangToggle() {
  var btn = document.getElementById('lang-toggle');
  if (!btn) return;
  btn.textContent = currentLang === 'en' ? '🇪🇸 ES' : '🇬🇧 EN';
  btn.title = currentLang === 'en' ? 'Cambiar a Español' : 'Switch to English';
}

// Run after DOM ready
document.addEventListener('DOMContentLoaded', function() {
  applyTranslations();
  updateLangToggle();
});

// Also re-apply after navigation (screens change)
var _origShowPage = window.showPage;
window.showPage = function(name, navEl) {
  if (_origShowPage) _origShowPage(name, navEl);
  setTimeout(applyTranslations, 50);
};
var _origShowCompPage = window.showCompPage;
window.showCompPage = function(name, navEl) {
  if (_origShowCompPage) _origShowCompPage(name, navEl);
  setTimeout(applyTranslations, 50);
};
